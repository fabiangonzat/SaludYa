-- SaludYA CRM: patients, doctors, scheduling, audit trail and messaging.
-- Run this migration with `supabase db push` or paste it in the Supabase SQL editor.

create extension if not exists pgcrypto;

create type public.user_role as enum ('patient', 'doctor', 'admin');
create type public.appointment_status as enum ('pendiente', 'confirmada', 'reprogramada', 'en-curso', 'completada', 'cancelada', 'no-asistio');
create type public.appointment_action as enum ('creada', 'confirmada', 'reprogramada', 'cancelada', 'completada');
create type public.modality as enum ('presencial', 'virtual');
create type public.gender as enum ('femenino', 'masculino');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null check (char_length(trim(full_name)) >= 3),
  email text not null unique,
  phone text,
  avatar_url text,
  role public.user_role not null default 'patient',
  birth_date date,
  gender public.gender,
  city text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.specialties (
  id bigint generated by default as identity primary key,
  name text not null unique,
  icon text,
  description text
);

create table public.doctors (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null unique references public.profiles(id) on delete cascade,
  specialty_id bigint references public.specialties(id) on delete set null,
  license text unique,
  bio text,
  price numeric(12,2) not null default 0 check (price >= 0),
  rating numeric(2,1) not null default 0 check (rating between 0 and 5),
  review_count integer not null default 0 check (review_count >= 0),
  years_experience integer not null default 0 check (years_experience >= 0),
  location text,
  city text,
  gender public.gender,
  university text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.doctor_languages (
  id bigint generated by default as identity primary key,
  doctor_id uuid not null references public.doctors(id) on delete cascade,
  language text not null,
  unique (doctor_id, language)
);

create table public.doctor_availability (
  id uuid primary key default gen_random_uuid(),
  doctor_id uuid not null references public.doctors(id) on delete cascade,
  day_of_week smallint not null check (day_of_week between 0 and 6),
  start_time time not null,
  end_time time not null,
  slot_duration_minutes smallint not null default 30 check (slot_duration_minutes between 10 and 120),
  modality public.modality not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  check (start_time < end_time)
);

create table public.appointments (
  id uuid primary key default gen_random_uuid(),
  patient_id uuid not null references public.profiles(id) on delete restrict,
  doctor_id uuid not null references public.doctors(id) on delete restrict,
  specialty_id bigint references public.specialties(id) on delete set null,
  date date not null,
  time time not null,
  modality public.modality not null,
  status public.appointment_status not null default 'pendiente',
  reason text not null check (char_length(trim(reason)) between 3 and 500),
  symptoms text,
  notes text,
  price numeric(12,2) not null default 0 check (price >= 0),
  duration_minutes smallint not null default 30 check (duration_minutes between 10 and 240),
  cancel_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.doctor_slots (
  id uuid primary key default gen_random_uuid(),
  doctor_id uuid not null references public.doctors(id) on delete cascade,
  date date not null,
  time time not null,
  modality public.modality not null,
  is_taken boolean not null default false,
  appointment_id uuid unique references public.appointments(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (doctor_id, date, time)
);

create table public.appointment_changes (
  id uuid primary key default gen_random_uuid(),
  appointment_id uuid not null references public.appointments(id) on delete cascade,
  action public.appointment_action not null,
  from_date date,
  from_time time,
  to_date date,
  to_time time,
  note text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.messages (
  id uuid primary key default gen_random_uuid(),
  sender_id uuid not null references public.profiles(id) on delete cascade,
  receiver_id uuid not null references public.profiles(id) on delete cascade,
  appointment_id uuid references public.appointments(id) on delete set null,
  content text not null check (char_length(trim(content)) between 1 and 4000),
  is_read boolean not null default false,
  created_at timestamptz not null default now(),
  check (sender_id <> receiver_id)
);

-- The clinical record is intentionally separated from the appointment. Only the
-- treating doctor and the patient may read it; an admin manages the CRM, not PHI.
create table public.medical_records (
  id uuid primary key default gen_random_uuid(),
  appointment_id uuid not null unique references public.appointments(id) on delete cascade,
  patient_id uuid not null references public.profiles(id) on delete restrict,
  doctor_id uuid not null references public.doctors(id) on delete restrict,
  diagnosis text,
  treatment text,
  clinical_notes text,
  follow_up_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index appointments_patient_date_idx on public.appointments(patient_id, date, time);
create index appointments_doctor_date_idx on public.appointments(doctor_id, date, time);
create index doctor_slots_available_idx on public.doctor_slots(doctor_id, date, time) where not is_taken;
create index messages_receiver_unread_idx on public.messages(receiver_id, is_read, created_at desc);

