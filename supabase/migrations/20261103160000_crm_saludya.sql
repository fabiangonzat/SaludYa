-- Auth sign-up creates the profile atomically. The browser must never be able to
-- self-assign the administrator role.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare requested_role public.user_role;
begin
  requested_role := case when new.raw_user_meta_data->>'role' = 'doctor' then 'doctor'::public.user_role else 'patient'::public.user_role end;
  insert into public.profiles (id, full_name, email, phone, birth_date, role, gender, city)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data->>'full_name'), ''), split_part(new.email, '@', 1)),
    new.email,
    nullif(new.raw_user_meta_data->>'phone', ''),
    nullif(new.raw_user_meta_data->>'birth_date', '')::date,
    requested_role,
    nullif(new.raw_user_meta_data->>'gender', '')::public.gender,
    nullif(new.raw_user_meta_data->>'city', '')
  ) on conflict (id) do update set email = excluded.email, updated_at = now();
  return new;
end; $$;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;
create or replace function public.is_own_doctor(p_doctor_id uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.doctors where id = p_doctor_id and profile_id = auth.uid());
$$;

