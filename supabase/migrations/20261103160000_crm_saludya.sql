-- Atomic booking: locks the generated slot, so two patients cannot take it.
create or replace function public.book_appointment(
  p_doctor_id uuid, p_date date, p_time time, p_modality public.modality,
  p_reason text, p_symptoms text default null, p_price numeric default 0,
  p_duration_minutes smallint default 30
) returns public.appointments
language plpgsql security definer set search_path = public as $$
declare v_slot public.doctor_slots; v_appointment public.appointments; v_specialty_id bigint;
begin
  if not exists (select 1 from public.profiles where id = auth.uid() and role = 'patient') then raise exception 'Solo un paciente puede reservar una cita'; end if;
  select * into v_slot from public.doctor_slots where doctor_id = p_doctor_id and date = p_date and time = p_time for update;
  if not found or v_slot.is_taken or v_slot.modality <> p_modality then raise exception 'El horario ya no está disponible'; end if;
  if p_date + p_time <= now() then raise exception 'No se puede reservar un horario pasado'; end if;
  select specialty_id into v_specialty_id from public.doctors where id = p_doctor_id and is_active;
  if not found then raise exception 'El médico no está disponible'; end if;
  insert into public.appointments (patient_id, doctor_id, specialty_id, date, time, modality, reason, symptoms, price, duration_minutes)
  values (auth.uid(), p_doctor_id, v_specialty_id, p_date, p_time, p_modality, p_reason, nullif(p_symptoms, ''), p_price, p_duration_minutes)
  returning * into v_appointment;
  update public.doctor_slots set is_taken = true, appointment_id = v_appointment.id where id = v_slot.id;
  insert into public.appointment_changes (appointment_id, action, to_date, to_time, created_by) values (v_appointment.id, 'creada', p_date, p_time, auth.uid());
  return v_appointment;
end; $$;

create or replace function public.change_appointment_status(p_appointment_id uuid, p_status public.appointment_status, p_note text default null)
returns public.appointments language plpgsql security definer set search_path = public as $$
declare v_appointment public.appointments; v_action public.appointment_action;
begin
  select * into v_appointment from public.appointments where id = p_appointment_id for update;
  if not found then raise exception 'Cita no encontrada'; end if;
  if not (v_appointment.patient_id = auth.uid() or public.is_own_doctor(v_appointment.doctor_id) or public.is_admin()) then raise exception 'No autorizado'; end if;
  if v_appointment.patient_id = auth.uid() and p_status <> 'cancelada' then raise exception 'El paciente solo puede cancelar una cita'; end if;
  update public.appointments set status = p_status, cancel_reason = case when p_status = 'cancelada' then nullif(p_note, '') else cancel_reason end where id = p_appointment_id returning * into v_appointment;
  if p_status = 'cancelada' then update public.doctor_slots set is_taken = false, appointment_id = null where appointment_id = p_appointment_id; v_action := 'cancelada';
  elsif p_status = 'confirmada' then v_action := 'confirmada';
  elsif p_status = 'completada' then v_action := 'completada';
  else v_action := 'creada'; end if;
  insert into public.appointment_changes (appointment_id, action, note, created_by) values (p_appointment_id, v_action, nullif(p_note, ''), auth.uid());
  return v_appointment;
end; $$;

create or replace function public.reschedule_appointment(p_appointment_id uuid, p_date date, p_time time)
returns public.appointments language plpgsql security definer set search_path = public as $$
declare v_appointment public.appointments; v_slot public.doctor_slots; v_old_date date; v_old_time time;
begin
  select * into v_appointment from public.appointments where id = p_appointment_id for update;
  if not found then raise exception 'Cita no encontrada'; end if;
  if not (v_appointment.patient_id = auth.uid() or public.is_own_doctor(v_appointment.doctor_id) or public.is_admin()) then raise exception 'No autorizado'; end if;
  v_old_date := v_appointment.date; v_old_time := v_appointment.time;
  select * into v_slot from public.doctor_slots where doctor_id = v_appointment.doctor_id and date = p_date and time = p_time for update;
  if not found or v_slot.is_taken or v_slot.modality <> v_appointment.modality then raise exception 'El horario ya no está disponible'; end if;
  update public.doctor_slots set is_taken = false, appointment_id = null where appointment_id = p_appointment_id;
  update public.doctor_slots set is_taken = true, appointment_id = p_appointment_id where id = v_slot.id;
  update public.appointments set date = p_date, time = p_time, status = 'reprogramada' where id = p_appointment_id returning * into v_appointment;
  insert into public.appointment_changes (appointment_id, action, from_date, from_time, to_date, to_time, created_by)
  values (p_appointment_id, 'reprogramada', v_old_date, v_old_time, p_date, p_time, auth.uid());
  return v_appointment;
end; $$;

