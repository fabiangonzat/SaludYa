import { Doctor, TimeSlot } from './doctors.models';
import { addDays, toYmd } from './doctors.query';

const TIMES = ['09:00', '10:30', '12:00', '15:00', '16:30', '18:00'] as const;

function slotsFor(
  now: Date,
  pattern: Array<{ offset: number; times: readonly string[]; modality: TimeSlot['modality']; taken?: string[] }>,
): TimeSlot[] {
  const slots: TimeSlot[] = [];
  for (const item of pattern) {
    const date = addDays(now, item.offset);
    if (date.getDay() === 0) continue;
    for (const time of item.times) {
      slots.push({
        date: toYmd(date),
        time,
        modality: item.modality,
        taken: item.taken?.includes(time) ?? false,
      });
    }
  }
  return slots;
}

